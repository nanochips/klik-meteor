create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  player text not null check (char_length(player) between 1 and 24),
  score integer not null check (score between 0 and 100000),
  created_at timestamptz not null default now()
);

alter table public.leaderboard enable row level security;

drop policy if exists "leaderboard can be read publicly" on public.leaderboard;
create policy "leaderboard can be read publicly" on public.leaderboard for select using (true);

drop policy if exists "leaderboard scores can be submitted publicly" on public.leaderboard;
create policy "leaderboard scores can be submitted publicly" on public.leaderboard for insert with check (true);